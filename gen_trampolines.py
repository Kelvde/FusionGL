#!/usr/bin/env python3
# 从内核导出符号并集生成 AArch64 尾跳转蹦床层
# 每个符号 3 条指令: adrp -> ldr -> br，参数寄存器 x0-x7/v0-v7 原样透传
import re, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
syms = [l.strip() for l in open(os.path.join(ROOT, 'trampoline_syms.txt')) if l.strip()]

PREFIX = ('gl', 'egl', 'glX', 'GL', 'EGL', 'gl4es', 'set_get', 'getMain')
# eglGetProcAddress 由 C 手写（需要优先查 GL 内核导出），不能进蹦床表
EXCLUDE = {'eglGetProcAddress'}
syms = [s for s in syms if s.startswith(PREFIX) and s not in EXCLUDE]
syms = sorted(set(syms))
N = len(syms)
assert N * 8 <= 32760, 'ldr imm12(scaled 8) 溢出，需要改两段式寻址'

a = []
a.append('/* AUTO-GENERATED by gen_trampolines.py - DO NOT EDIT */')
a.append('/* FusionGL v3.0 AArch64 tail-call trampolines */')
a.append('    .text')
a.append('    .balign 16')
a.append('    .globl fus_null_stub')
a.append('    .type fus_null_stub, %function')
a.append('fus_null_stub:')
a.append('    mov x0, #0')
a.append('    ret')
a.append('    .size fus_null_stub, . - fus_null_stub')
a.append('')
a.append('    .macro TRAMP name, off')
a.append('    .globl \\name')
a.append('    .type \\name, %function')
a.append('\\name:')
a.append('    adrp x9, g_slots')
a.append('    ldr  x9, [x9, #\\off]')
a.append('    br   x9')
a.append('    .size \\name, . - \\name')
a.append('    .endm')
a.append('')
for i, s in enumerate(syms):
    a.append('    TRAMP %s, %d' % (s, i * 8))
a.append('')
a.append('    .bss')
a.append('    .balign 4096')
a.append('    .globl g_slots')
a.append('    .hidden g_slots')
a.append('    .type g_slots, %object')
a.append('g_slots:')
a.append('    .zero %d' % (N * 8))
a.append('    .size g_slots, . - g_slots')
a.append('')
open(os.path.join(HERE, 'trampolines.S'), 'w').write('\n'.join(a) + '\n')

c = []
c.append('/* AUTO-GENERATED by gen_trampolines.py - DO NOT EDIT */')
c.append('#include <stddef.h>')
c.append('extern void *g_slots[];')
c.append('const char * const g_sym_names[] = {')
for s in syms:
    c.append('    "%s",' % s)
c.append('};')
c.append('const int g_slot_count = %d;' % N)
c.append('')
open(os.path.join(HERE, 'sym_names.c'), 'w').write('\n'.join(c) + '\n')

print('generated %d trampolines, g_slots %d bytes' % (N, N * 8))
